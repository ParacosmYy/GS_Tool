/** @brief CRC-8 查表计算 @param data 数据指针 @param len 长度 @return CRC-8值 */
quint64 DataChecksumVerifier::computeCRC8(const uint8_t *data, int len)
{
    uint8_t crc = 0x00;
    for (int i = 0; i < len; ++i)
        crc = s_crc8Table[crc ^ data[i]];
    return crc;
}

/** @brief CRC-16/CCITT 查表计算(初始0xFFFF) @param data 数据指针 @param len 长度 @return CRC-16值 */
quint64 DataChecksumVerifier::computeCRC16_CCITT(const uint8_t *data, int len)
{
    uint16_t crc = 0xFFFF;
    for (int i = 0; i < len; ++i)
        crc = (crc << 8) ^ s_crc16CcittTable[((crc >> 8) ^ data[i]) & 0xFF];
    return crc;
}

