/** @brief 8位异或 @param data 数据指针 @param len 长度 @return XOR结果 */
quint64 DataChecksumVerifier::computeXOR8(const uint8_t *data, int len)
{
    uint8_t result = 0;
    for (int i = 0; i < len; ++i)
        result ^= data[i];
    return result;
}

/**
 * @brief 通用累加和计算
 * @param data 数据指针
 * @param len 长度
 * @param bits 位宽(8/16/32)
 * @param bigEndian true=大端序(Sum16_BE/Sum32)，false=小端序(Sum16_LE)
 * @return 累加和结果
 */
quint64 DataChecksumVerifier::computeSum(const uint8_t *data, int len, int bits, bool bigEndian)
{
    if (bits == 8) {
        uint16_t sum = 0;
        for (int i = 0; i < len; ++i)
            sum += data[i];
        return sum & 0xFF;
    }
    if (bits == 16) {
        uint32_t sum = 0;
        if (bigEndian) {
            for (int i = 0; i + 1 < len; i += 2)
                sum += (static_cast<uint16_t>(data[i]) << 8) | data[i + 1];
            if (len % 2)
                sum += static_cast<uint16_t>(data[len - 1]) << 8;
        } else {
            for (int i = 0; i + 1 < len; i += 2)
                sum += data[i] | (static_cast<uint16_t>(data[i + 1]) << 8);
            if (len % 2)
                sum += data[len - 1];
        }
        return sum & 0xFFFF;
    }
    /* bits == 32, Sum32_LE: 小端序四字节累加 */
    quint64 sum = 0;
    for (int i = 0; i + 3 < len; i += 4) {
        sum += static_cast<uint32_t>(data[i])
               | (static_cast<uint32_t>(data[i + 1]) << 8)
               | (static_cast<uint32_t>(data[i + 2]) << 16)
               | (static_cast<uint32_t>(data[i + 3]) << 24);
    }
    int remaining = len % 4;
    int tail = len - remaining;
    for (int i = tail; i < len; ++i)
        sum += static_cast<uint32_t>(data[i]) << (8 * (i - tail));
    return sum & 0xFFFFFFFF;
}

// ─────────────────────────── 私有: 补码系列 ───────────────────────────

/**
 * @brief 16位一进制反码求和(IP/TCP/UDP风格)
 * @param data 数据指针
 * @param len 长度
 * @return 反码校验值
 */
quint64 DataChecksumVerifier::computeOnesComplement16(const uint8_t *data, int len)
{
    uint32_t sum = 0;
    for (int i = 0; i + 1 < len; i += 2)
        sum += (static_cast<uint16_t>(data[i]) << 8) | data[i + 1];
    if (len % 2)
        sum += static_cast<uint16_t>(data[len - 1]) << 8;
    while (sum >> 16)
        sum = (sum & 0xFFFF) + (sum >> 16);
    return static_cast<uint16_t>(~sum);
}

/**
 * @brief 16位二进制补码求和
 * @param data 数据指针
 * @param len 长度
 * @return 补码校验值
 */
quint64 DataChecksumVerifier::computeTwosComplement16(const uint8_t *data, int len)
{
    uint32_t sum = 0;
    for (int i = 0; i + 1 < len; i += 2)
        sum += (static_cast<uint16_t>(data[i]) << 8) | data[i + 1];
    if (len % 2)
        sum += static_cast<uint16_t>(data[len - 1]) << 8;
    return static_cast<uint16_t>((~sum + 1) & 0xFFFF);
}

// ─────────────────────────── 私有: Fletcher系列 ───────────────────────────

/**
 * @brief Fletcher校验计算
 * @param data 数据指针
 * @param len 长度
 * @param bits 位宽(8/16/32)
 * @return Fletcher校验值
 */
quint64 DataChecksumVerifier::computeFletcher(const uint8_t *data, int len, int bits)
{
    if (bits == 8) {
        uint16_t sum1 = 0, sum2 = 0;
        for (int i = 0; i < len; ++i) {
            uint8_t hi = (data[i] >> 4) & 0x0F;
            uint8_t lo = data[i] & 0x0F;
            sum1 = (sum1 + hi) % 15;
            sum2 = (sum2 + sum1) % 15;
            sum1 = (sum1 + lo) % 15;
            sum2 = (sum2 + sum1) % 15;
        }
        return (static_cast<uint16_t>(sum2) << 4) | sum1;
    }
    if (bits == 16) {
        uint16_t sum1 = 0, sum2 = 0;
        for (int i = 0; i < len; ++i) {
            sum1 = (sum1 + data[i]) % 255;
            sum2 = (sum2 + sum1) % 255;
        }
        return (static_cast<uint16_t>(sum2) << 8) | sum1;
    }
    /* bits == 32: Fletcher-32 */
    uint32_t sum1 = 0, sum2 = 0;
    for (int i = 0; i + 1 < len; i += 2) {
        uint16_t word = (static_cast<uint16_t>(data[i]) << 8) | data[i + 1];
        sum1 = (sum1 + word) % 65535;
        sum2 = (sum2 + sum1) % 65535;
    }
    if (len % 2) {
        uint16_t word = static_cast<uint16_t>(data[len - 1]) << 8;
        sum1 = (sum1 + word) % 65535;
        sum2 = (sum2 + sum1) % 65535;
    }
    return (static_cast<uint32_t>(sum2) << 16) | sum1;
}

// ─────────────────────────── 私有: Adler-32 ───────────────────────────

/**
 * @brief Adler-32 校验计算(zlib使用)
 * @param data 数据指针
 * @param len 长度
 * @return Adler-32值
 */
quint64 DataChecksumVerifier::computeAdler32(const uint8_t *data, int len)
{
    const uint32_t MOD = 65521;
    uint32_t a = 1, b = 0;
    int idx = 0;
    while (idx < len) {
        int chunkLen = qMin(len - idx, 5552);
        for (int i = 0; i < chunkLen; ++i) {
            a += data[idx + i];
            b += a;
        }
        a %= MOD;
        b %= MOD;
        idx += chunkLen;
    }
    return (static_cast<uint32_t>(b) << 16) | a;
}

// ─────────────────────────── 核心分派 ───────────────────────────

/**
 * @brief 静态计算校验和(无统计副作用)
 * @param algo 算法枚举
 * @param data 输入数据
 * @param startPos 起始偏移
 * @param length 长度(-1表示到末尾)
 * @return 校验和结果
 */
quint64 DataChecksumVerifier::compute(Algorithm algo, const QByteArray &data,
                                      int startPos, int length)
{
    if (data.isEmpty())
        return 0;

    int start = qBound(0, startPos, data.size() - 1);
    int len = (length < 0) ? (data.size() - start) : qMin(length, data.size() - start);
    if (len <= 0)
        return 0;

    const uint8_t *ptr = reinterpret_cast<const uint8_t *>(data.constData()) + start;

    switch (algo) {
    case Algorithm::CRC8:             return computeCRC8(ptr, len);
    case Algorithm::CRC16_CCITT:      return computeCRC16_CCITT(ptr, len);
    case Algorithm::CRC16_MODBUS:     return computeCRC16_MODBUS(ptr, len);
    case Algorithm::CRC16_XMODEM:    return computeCRC16_XMODEM(ptr, len);
    case Algorithm::CRC32:            return computeCRC32(ptr, len);
    case Algorithm::CRC32C:           return computeCRC32C(ptr, len);
    case Algorithm::XOR8:             return computeXOR8(ptr, len);
    case Algorithm::Sum8:             return computeSum(ptr, len, 8, true);
    case Algorithm::Sum16_LE:         return computeSum(ptr, len, 16, false);
    case Algorithm::Sum16_BE:         return computeSum(ptr, len, 16, true);
    case Algorithm::Sum32_LE:         return computeSum(ptr, len, 32, false);
    case Algorithm::OnesComplement16: return computeOnesComplement16(ptr, len);
    case Algorithm::TwosComplement16: return computeTwosComplement16(ptr, len);
    case Algorithm::Fletcher8:        return computeFletcher(ptr, len, 8);
    case Algorithm::Fletcher16:       return computeFletcher(ptr, len, 16);
    case Algorithm::Fletcher32:       return computeFletcher(ptr, len, 32);
    case Algorithm::Adler32:          return computeAdler32(ptr, len);
    }
    return 0;
}
